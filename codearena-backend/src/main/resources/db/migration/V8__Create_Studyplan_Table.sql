-- =========================================================
-- STUDY PLANS
-- =========================================================

CREATE TABLE study_plans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,

    name VARCHAR(100) NOT NULL,

    slug VARCHAR(100) NOT NULL,

    description TEXT,

    created_at TIMESTAMP NOT NULL,

    updated_at TIMESTAMP NOT NULL,

    CONSTRAINT pk_study_plans
        PRIMARY KEY (id),

    CONSTRAINT uk_study_plans_name
        UNIQUE (name),

    CONSTRAINT uk_study_plans_slug
        UNIQUE (slug)
);


-- =========================================================
-- STUDY PLAN PROBLEMS
-- =========================================================

CREATE TABLE study_plan_problems (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY,

    study_plan_id BIGINT NOT NULL,

    problem_id BIGINT NOT NULL,

    order_number INTEGER NOT NULL,

    CONSTRAINT pk_study_plan_problems
        PRIMARY KEY (id),

    CONSTRAINT uk_study_plan_problem
        UNIQUE (study_plan_id, problem_id),

    CONSTRAINT fk_study_plan_problem_plan
        FOREIGN KEY (study_plan_id)
        REFERENCES study_plans(id)
        ON DELETE CASCADE,

    CONSTRAINT fk_study_plan_problem_problem
        FOREIGN KEY (problem_id)
        REFERENCES problems(id)
        ON DELETE CASCADE
);